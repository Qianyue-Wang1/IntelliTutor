package com.intellitutor.scut.modules.experiment.domain;

public enum StudentState {
    MUST_CHANGE_PASSWORD,
    WAITING_LECTURE, LECTURE_IN_PROGRESS,
    WAITING_PRETEST, PRETEST_IN_PROGRESS,
    WAITING_GROUP_ASSIGNMENT,
    WAITING_MODE_SELECTION,
    WAITING_ROUND_1_TUTOR, ROUND_1_TUTOR_IN_PROGRESS,
    WAITING_ROUND_1_QUIZ, ROUND_1_QUIZ_IN_PROGRESS,
    WAITING_ROUND_2_TUTOR, ROUND_2_TUTOR_IN_PROGRESS,
    WAITING_ROUND_2_QUIZ, ROUND_2_QUIZ_IN_PROGRESS,
    WAITING_ROUND_3_TUTOR, ROUND_3_TUTOR_IN_PROGRESS,
    WAITING_ROUND_3_QUIZ, ROUND_3_QUIZ_IN_PROGRESS,
    WAITING_ROUND_4_TUTOR, ROUND_4_TUTOR_IN_PROGRESS,
    WAITING_ROUND_4_QUIZ, ROUND_4_QUIZ_IN_PROGRESS,
    WAITING_ROUND_5_TUTOR, ROUND_5_TUTOR_IN_PROGRESS,
    WAITING_ROUND_5_QUIZ, ROUND_5_QUIZ_IN_PROGRESS,
    WAITING_POSTTEST, POSTTEST_IN_PROGRESS,
    WAITING_QUESTIONNAIRE, QUESTIONNAIRE_IN_PROGRESS,
    WAITING_CREDENTIAL,
    EXPERIMENT_FINISHED;

    public boolean canEnter(GlobalStage stage) {
        return switch (stage) {
            case LECTURE -> this == WAITING_LECTURE || this == LECTURE_IN_PROGRESS;
            case PRETEST -> this == WAITING_PRETEST || this == PRETEST_IN_PROGRESS;
            case ROUND_1_TUTOR -> this == WAITING_ROUND_1_TUTOR || this == ROUND_1_TUTOR_IN_PROGRESS;
            case ROUND_1_QUIZ -> this == WAITING_ROUND_1_QUIZ || this == ROUND_1_QUIZ_IN_PROGRESS;
            case ROUND_2_TUTOR -> this == WAITING_ROUND_2_TUTOR || this == ROUND_2_TUTOR_IN_PROGRESS;
            case ROUND_2_QUIZ -> this == WAITING_ROUND_2_QUIZ || this == ROUND_2_QUIZ_IN_PROGRESS;
            case ROUND_3_TUTOR -> this == WAITING_ROUND_3_TUTOR || this == ROUND_3_TUTOR_IN_PROGRESS;
            case ROUND_3_QUIZ -> this == WAITING_ROUND_3_QUIZ || this == ROUND_3_QUIZ_IN_PROGRESS;
            case ROUND_4_TUTOR -> this == WAITING_ROUND_4_TUTOR || this == ROUND_4_TUTOR_IN_PROGRESS;
            case ROUND_4_QUIZ -> this == WAITING_ROUND_4_QUIZ || this == ROUND_4_QUIZ_IN_PROGRESS;
            case ROUND_5_TUTOR -> this == WAITING_ROUND_5_TUTOR || this == ROUND_5_TUTOR_IN_PROGRESS;
            case ROUND_5_QUIZ -> this == WAITING_ROUND_5_QUIZ || this == ROUND_5_QUIZ_IN_PROGRESS;
            case POSTTEST -> this == WAITING_POSTTEST || this == POSTTEST_IN_PROGRESS;
            case QUESTIONNAIRE -> this == WAITING_QUESTIONNAIRE || this == QUESTIONNAIRE_IN_PROGRESS;
            case FINISHED -> this == EXPERIMENT_FINISHED;
            default -> false;
        };
    }

    public boolean inProgress() { return name().endsWith("_IN_PROGRESS"); }
}
